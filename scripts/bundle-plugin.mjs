import { build } from "esbuild";
import { readFileSync, mkdirSync } from "node:fs";

// Bundles the plugin-facing entrypoints into single stdlib-only .mjs files
// committed under plugin/dist/. Claude Code plugins are git checkouts with no
// npm-install step, so these must carry their (pure-JS) dependencies inline.
// The heavy native runtime stays in ~/.recall/app, installed by /recall:setup.

const version = JSON.parse(readFileSync(new URL("../package.json", import.meta.url))).version;
mkdirSync(new URL("../plugin/dist", import.meta.url), { recursive: true });

const entries = [
  { in: "dist/hooks/stop-hook.js", out: "plugin/dist/stop-hook.mjs" },
  { in: "dist/hooks/prompt-hook.js", out: "plugin/dist/prompt-hook.mjs" },
  { in: "dist/mcp/proxy.js", out: "plugin/dist/mcp-proxy.mjs" },
];

for (const e of entries) {
  await build({
    entryPoints: [e.in],
    outfile: e.out,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    define: {
      PLUGIN_BUILD: "true",
      // version.ts uses createRequire on package.json, which doesn't exist
      // relative to an installed plugin bundle — inline the version instead.
    },
    banner: {
      js: `// recall plugin bundle v${version} — generated by scripts/bundle-plugin.mjs; do not edit.`,
    },
    logLevel: "warning",
  });
  console.log(`bundled ${e.in} -> ${e.out}`);
}
